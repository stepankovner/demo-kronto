// Неразрывные пробелы: тире не уходит в начало строки, короткие предлоги
// и союзы не висят в конце, число не отрывается от «₽» и следующего слова.

const NBSP = " ";
const SHORT = /(^|[\s(«])(в|и|с|к|о|у|а|я|на|по|не|за|от|до|из|со|во|ко|об|но|ли|же|то|их|ее|её|он|мы|вы)\s/giu;

export function typo(text) {
  return String(text)
    .replace(/ (—|–) /g, `${NBSP}$1 `)
    .replace(SHORT, `$1$2${NBSP}`)
    .replace(SHORT, `$1$2${NBSP}`) // второй проход — для «и в», «а не»
    .replace(/(\d) (?=[\d₽%]|[а-яё])/giu, `$1${NBSP}`);
}
